#!/usr/bin/env node
/**
 * Writes the host routing files from shared/spaRoutes.js so they cannot drift:
 *   - public/_redirects          (Netlify: SPA allow-list + real 404 for everything else)
 *   - render.yaml `routes:` block (Render static site, between the BEGIN/END markers)
 * Usage:
 *   node scripts/generate-host-config.mjs          write the files
 *   node scripts/generate-host-config.mjs --check  exit 1 if a file is out of date (used by tests)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { spaRewriteSources } from "../shared/spaRoutes.js";
import { SEO_REDIRECTS } from "../shared/seoRedirects.js";

const root = new URL("../", import.meta.url);
const REDIRECTS = fileURLToPath(new URL("public/_redirects", root));
const RENDER = fileURLToPath(new URL("render.yaml", root));
const BEGIN = "    # BEGIN generated routes (scripts/generate-host-config.mjs, from shared/spaRoutes.js)";
const END = "    # END generated routes";

export function buildRedirects() {
  const lines = [
    "# Gadvede Trekkers — Netlify routing (generated by scripts/generate-host-config.mjs; edit shared/spaRoutes.js).",
    "# Only the URLs the React app answers are rewritten to index.html (200). Everything else gets",
    "# public/404.html with a real HTTP 404, instead of the home page with 200 (soft 404).",
    "# Rules are not forced, so real files (/robots.txt, /sitemap.xml, /trips/*.jpg, /assets/*) still win.",
    "",
    "# Duplicate URLs: permanent redirect to the page that replaces them (shared/seoRedirects.js).",
    ...Object.entries(SEO_REDIRECTS).map(([from, to]) => `${from.padEnd(34)} ${to}   301`),
    "",
    ...spaRewriteSources().map((src) => `${src.padEnd(34)} /index.html   200`),
    "",
    "/*                                 /404.html     404",
    "",
  ];
  return lines.join("\n");
}

export function buildRenderRoutes() {
  const redirects = Object.entries(SEO_REDIRECTS).flatMap(([from, to]) => [
    "      - type: redirect",
    `        source: ${from}`,
    `        destination: ${to}`,
  ]);
  const rewrites = spaRewriteSources().flatMap((src) => [
    "      - type: rewrite",
    `        source: ${src}`,
    "        destination: /index.html",
  ]);
  return [BEGIN, "    routes:", ...redirects, ...rewrites, END].join("\n");
}

export function applyRenderRoutes(yaml) {
  const a = yaml.indexOf(BEGIN);
  const b = yaml.indexOf(END);
  if (a < 0 || b < 0) throw new Error("render.yaml is missing the BEGIN/END generated routes markers");
  return yaml.slice(0, a) + buildRenderRoutes() + yaml.slice(b + END.length);
}

const check = process.argv.includes("--check");
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const nextRedirects = buildRedirects();
  const nextRender = applyRenderRoutes(readFileSync(RENDER, "utf8"));
  const stale = [];
  if (readFileSync(REDIRECTS, "utf8") !== nextRedirects) stale.push("public/_redirects");
  if (readFileSync(RENDER, "utf8") !== nextRender) stale.push("render.yaml");
  if (check) {
    if (stale.length) { console.error(`Out of date: ${stale.join(", ")}. Run: node scripts/generate-host-config.mjs`); process.exit(1); }
    console.log("host config is up to date");
  } else {
    writeFileSync(REDIRECTS, nextRedirects);
    writeFileSync(RENDER, nextRender);
    console.log(`wrote public/_redirects and render.yaml (${spaRewriteSources().length} rewrite rules)`);
  }
}
